const dictionaries: Record<Lang, Partial<Record<Key, string>>> = { en, bn };
const RTL = new Set(['ur', 'ar']);

export function pickLanguage(preferred: readonly string[] = typeof navigator === 'undefined' ? [] : navigator.languages): Lang {
  for (const tag of preferred) {
    const base = tag.toLowerCase().split('-')[0] ?? '';

    if (base === 'bn') return 'bn';
    if (base === 'en') return 'en';
  }

  return 'en';
}

export function isRtl(tag: string): boolean {
  return RTL.has(tag.toLowerCase().split('-')[0] ?? '');
}

export function translator(lang: Lang) {
  return (key: Key, vars: Record<string, string | number> = {}): string => {
    const template = dictionaries[lang][key] ?? en[key];

    return template.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? ''));
  };
}
